import { createFileRoute, Link } from "@tanstack/react-router";
import { format, parseISO, addDays } from "date-fns";
import { Info, ShieldCheck, ChevronRight } from "lucide-react";
import { Button } from "@/components/ui/button";
import { PageHeader, Panel, DomainBadge, IntensityPill, Loading, ErrorState, Empty } from "@/components/ui-kit";
import { todayISO, useActivePlan } from "@/lib/data";
import { cn } from "@/lib/utils";

export const Route = createFileRoute("/_authenticated/plan")({
  head: () => ({ meta: [{ title: "My Plan — Human Performance AI" }, { name: "description", content: "Your weekly training calendar and plan rationale." }] }),
  component: PlanPage,
});

function PlanPage() {
  const { data, isLoading, error, refetch } = useActivePlan();
  if (isLoading) return <Loading />;
  if (error) return <ErrorState error={error} onRetry={() => refetch()} />;
  if (!data) return <Empty title="No plan yet" action={<Button asChild><Link to="/settings">Generate plan</Link></Button>}>Complete your profile and generate a plan.</Empty>;

  const today = todayISO();
  const start = parseISO(data.plan.week_start);

  return (
    <>
      <PageHeader eyebrow={`Week of ${format(start, "d MMM yyyy")}`} title="My Plan" description="A 7-day block generated by the rules-based planner from your assessment." />
      <div className="grid gap-4 lg:grid-cols-3">
        <div className="space-y-3 lg:col-span-2">
          {Array.from({ length: 7 }).map((_, i) => {
            const iso = format(addDays(start, i), "yyyy-MM-dd");
            const w = data.workouts.find((x) => x.scheduled_date === iso);
            return (
              <div key={iso} className={cn("flex items-center gap-4 rounded-xl border bg-card p-4", iso === today ? "border-primary" : "border-border")}>
                <div className="w-14 shrink-0 text-center">
                  <p className="stat-num text-xs text-muted-foreground">{format(addDays(start, i), "EEE").toUpperCase()}</p>
                  <p className="stat-num text-2xl">{format(addDays(start, i), "d")}</p>
                </div>
                {w ? (
                  <Link to="/workout/$id" params={{ id: w.id }} className="flex flex-1 items-center justify-between gap-3">
                    <div>
                      <div className="flex flex-wrap items-center gap-2"><DomainBadge domain={w.domain} /><IntensityPill level={w.intensity} /></div>
                      <p className="mt-1.5 font-semibold">{w.title}</p>
                      <p className="text-xs capitalize text-muted-foreground">{w.duration_min} min · {w.focus}</p>
                    </div>
                    <div className="flex items-center gap-2">
                      <span className={cn("rounded-full px-2 py-0.5 text-xs capitalize", w.status === "completed" ? "bg-primary/15 text-primary" : w.status === "skipped" ? "bg-muted text-muted-foreground" : "bg-secondary")}>{w.status}</span>
                      <ChevronRight className="size-4 text-muted-foreground" />
                    </div>
                  </Link>
                ) : (
                  <div className="flex-1"><p className="font-medium text-muted-foreground">Rest day</p><p className="text-xs text-muted-foreground">Optional: easy walk, mobility or breathing.</p></div>
                )}
              </div>
            );
          })}
        </div>
        <div className="space-y-4">
          <Panel title="Why this plan" action={<Info className="size-4 text-muted-foreground" />}>
            <ul className="space-y-3 text-sm">{data.plan.rationale.map((r, i) => <li key={i} className="flex gap-2"><span className="stat-num text-primary">0{i + 1}</span><span>{r}</span></li>)}</ul>
            <p className="mt-4 text-xs text-muted-foreground">Generated by deterministic rules — no AI model was used.</p>
          </Panel>
          <Panel title="Safety notes" action={<ShieldCheck className="size-4 text-teal" />}>
            <ul className="list-disc space-y-2 pl-4 text-sm text-muted-foreground">{data.plan.safety_notes.map((s, i) => <li key={i}>{s}</li>)}</ul>
          </Panel>
        </div>
      </div>
    </>
  );
}
